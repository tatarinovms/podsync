#!/usr/bin/env python3
"""Compile the Podsync DTCG theme into both copies of admin.css."""

import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
START = "/* PODSYNC THEME: generated by scripts/build_podsync_theme.py */"
END = "/* END PODSYNC THEME */"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    themes = json.loads((ROOT / "tokens/podsync.json").read_text())
    lines = [START]
    for theme, tokens in themes.items():
        selector = ':root, [data-theme="latte"]' if theme == "latte" else '[data-theme="mocha"]'
        lines.append(selector + " {")
        for name, token in tokens.items():
            def alias(match):
                source, key = match[1].split(".", 1)
                if source not in themes or key not in themes[source]:
                    raise ValueError("Unknown token: " + match[1])
                return "var(--" + key + ")"
            value = re.sub(r"\{([^}]+)\}", alias, token["$value"])
            lines.append(f"    --{name}: {value};")
        lines.append("}")
    lines.append(END)
    generated = "\n".join(lines)
    source = ROOT / "services/web/ui/admin.css"
    css = source.read_text()
    expected = generated + css[css.index(END) + len(END):]
    targets = [source, ROOT / "html/admin.css"]
    if args.check:
        stale = [str(p.relative_to(ROOT)) for p in targets if p.read_text() != expected]
        if stale:
            raise SystemExit("Stale theme output: " + ", ".join(stale))
        print("Podsync theme: generated output and mirror are current")
    else:
        for target in targets:
            target.write_text(expected)


if __name__ == "__main__":
    main()
